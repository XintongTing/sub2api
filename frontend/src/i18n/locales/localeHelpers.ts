export function toTraditionalText(input: string): string {
  let output = input
  for (const [source, target] of Object.entries(traditionalPhrases)) {
    output = output.split(source).join(target)
  }
  return Array.from(output, (char) => traditionalChars[char] ?? char).join('')
}
