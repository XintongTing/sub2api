type MessageValue = string | number | boolean | null | undefined | MessageObject | MessageValue[]
type MessageObject = { [key: string]: MessageValue }
type PartialMessage<T> = T extends Array<infer U>
  ? Array<PartialMessage<U>>
  : T extends MessageObject
    ? { [K in keyof T]?: PartialMessage<T[K]> }
    : T

export function deepMergeMessages<T extends MessageValue>(base: T, override: PartialMessage<T>): T {
  if (Array.isArray(base)) {
    return (Array.isArray(override) ? override : base) as T
  }

  if (!isPlainObject(base) || !isPlainObject(override)) {
    return (override === undefined ? base : override) as T
  }

  const merged: MessageObject = { ...base }
  for (const [key, value] of Object.entries(override)) {
    const baseValue = (base as MessageObject)[key]
    merged[key] = deepMergeMessages(baseValue, value as MessageValue)
  }
  return merged as T
}

export function mapMessageStrings<T extends MessageValue>(value: T, mapper: (text: string) => string): T {
  if (typeof value === 'string') {
    return mapper(value) as T
  }

  if (Array.isArray(value)) {
    return value.map((item) => mapMessageStrings(item, mapper)) as T
  }

  if (!isPlainObject(value)) {
    return value
  }

  const mapped: MessageObject = {}
  for (const [key, child] of Object.entries(value)) {
    mapped[key] = mapMessageStrings(child, mapper)
  }
  return mapped as T
}

function isPlainObject(value: unknown): value is MessageObject {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value)
}

